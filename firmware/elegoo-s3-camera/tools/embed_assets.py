root=Path(__file__).resolve().parents[1]
parts=['// Generated by tools/embed_assets.py from public web assets.\n#pragma once\n']
for name,filename in [('SETUP_HTML','setup.html'),('SETUP_JS','setup.js')]:
 text=(root/'web'/filename).read_text()
 assert ')CHARLIE_ASSET"' not in text
 parts.append(f'const char {name}[] = R"CHARLIE_ASSET({text})CHARLIE_ASSET";\n')
(root/'ElegooS3Camera'/'SetupAssets.h').write_text(''.join(parts))
